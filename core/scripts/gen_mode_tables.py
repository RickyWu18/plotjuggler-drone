"""Generates the built-in flight-mode tables from the MAVLink ardupilotmega.xml dialect.

usage: gen_mode_tables.py <ardupilotmega.xml> <output.inc>

Reads the COPTER_MODE, PLANE_MODE, ROVER_MODE, SUB_MODE and TRACKER_MODE enums (the name of an entry is its
<description> text, else the enum name without its prefix) and writes one
`constexpr ModeEntry k<Vehicle>Modes[]` array per enum, to be #included by core/src/ardupilot/vehicle.cpp (which
defines ModeEntry). The output is only rewritten when its content changes, so an unchanged table does not rebuild.
"""

import sys
import xml.etree.ElementTree as ET

ENUMS = ["COPTER_MODE", "PLANE_MODE", "ROVER_MODE", "SUB_MODE", "TRACKER_MODE"]


def render(xml_path: str) -> str:
    root = ET.parse(xml_path).getroot()
    enums = {e.get("name"): e for e in root.iter("enum")}

    out = ["// Generated by core/scripts/gen_mode_tables.py from ardupilotmega.xml. Do not edit.\n"]
    for enum_name in ENUMS:
        enum = enums.get(enum_name)
        if enum is None:
            raise SystemExit(f"error: enum {enum_name} not found in {xml_path}")
        prefix = enum_name + "_"
        rows = []
        for entry in enum.findall("entry"):
            name = entry.get("name", "")
            if not name.startswith(prefix):
                raise SystemExit(f"error: {name} does not start with {prefix}")
            # The shown name is the entry's <description> (e.g. "ALT HOLD"); the enum name only backs it up.
            description = " ".join((entry.findtext("description") or "").split())
            text = description or name[len(prefix):]
            rows.append((int(entry.get("value")), text.replace("\\", "\\\\").replace('"', '\\"')))
        if not rows:
            raise SystemExit(f"error: enum {enum_name} has no entries in {xml_path}")
        if len({value for value, _ in rows}) != len(rows):
            raise SystemExit(f"error: enum {enum_name} has a duplicate value")

        table = enum_name.removesuffix("_MODE").capitalize()
        out.append(f"constexpr ModeEntry k{table}Modes[] = {{")
        out.extend(f'    {{{value}, "{name}"}},' for value, name in rows)
        out.append("};\n")
    return "\n".join(out)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    xml_path, output = sys.argv[1], sys.argv[2]
    content = render(xml_path)
    try:
        with open(output, encoding="utf-8") as f:
            if f.read() == content:
                return
    except FileNotFoundError:
        pass
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


if __name__ == "__main__":
    main()
